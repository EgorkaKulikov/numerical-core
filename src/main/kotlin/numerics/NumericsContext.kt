package numerics

import numerics.backend.Backends
import numerics.backend.LinAlgBackend

/**
 * Явный контекст численных вычислений: ЧЕМ считать и КАК распараллеливать.
 *
 * Заменяет собой глобальное мутируемое состояние, которое раньше жило в
 * `Backends.use()/reset()` и `ParallelAssembly.parallelEnabled`. Глобальный
 * переключатель означал, что результат вызова зависел от того, что успел
 * выставить сосед по JVM (в тестах — от порядка выполнения), и что «вернуть как
 * было» приходилось руками в `finally`. Здесь обе настройки — неизменяемые поля,
 * которые путешествуют вместе с решателем.
 *
 * Контекст передаётся ПОСЛЕДНИМ параметром конструктора со значением по умолчанию
 * [default], поэтому существующий код, которому безразличен бэкенд, не меняется.
 *
 * @property backend реализация линейной алгебры; по умолчанию — стартовый выбор
 *           [Backends.default] (нативный multik при доступности, иначе reference).
 * @property parallel разрешена ли параллельная сборка матриц
 *           ([ParallelAssembly]); на результат не влияет (сборка побитово
 *           идентична), влияет только на время.
 */
data class NumericsContext(
    val backend: LinAlgBackend = Backends.default(),
    val parallel: Boolean = true,
) {
    companion object {
        /**
         * Разделяемый экземпляр контекста по умолчанию.
         *
         * Значение параметра по умолчанию в Kotlin вычисляется при КАЖДОМ вызове,
         * поэтому `ctx: NumericsContext = NumericsContext()` создавал бы объект на
         * каждое построение семейства функционалов и каждого решателя. Здесь объект
         * один на процесс.
         *
         * `lazy`, а не `val` в инициализаторе companion: [Backends.default] может
         * бросить (неизвестный/недоступный запрошенный бэкенд), а исключение из
         * инициализатора класса вырождается в `NoClassDefFoundError` без текста
         * причины при втором обращении. `lazy` исключение не кэширует.
         */
        private val shared: Lazy<NumericsContext> = lazy { NumericsContext() }

        /** Контекст по умолчанию: стартовый бэкенд, параллельная сборка включена. */
        fun default(): NumericsContext = shared.value

        /**
         * Требует, чтобы ЗАВИСИМОСТЬ решателя считала ТЕМ ЖЕ контекстом, что и сам решатель.
         *
         * ЗАЧЕМ. Контекст хранится в НЕСКОЛЬКИХ объектах одной задачи: у семейства
         * функционалов (решает крошечные СЛАУ при построении), у сплайн-пространства
         * (считает стабилизатор `Omega`) и у самого решателя. Если они разойдутся,
         * ЧАСТИ ОДНОЙ ЗАДАЧИ посчитаются РАЗНЫМИ реализациями LU. Ошибка не даёт
         * ни исключения, ни предупреждения — только сдвиг младших битов результата,
         * который невозможно связать с причиной постфактум.
         *
         * Сравнение ПО ЗНАЧЕНИЮ ([NumericsContext] — `data class`), а не по ссылке: два
         * независимо созданных `NumericsContext(backend = ReferenceBackend)` описывают одну
         * и ту же конфигурацию и обязаны считаться совместимыми.
         *
         * @param owner имя класса-владельца для сообщения об ошибке.
         * @param expected контекст самого решателя.
         * @param dependency имя параметра-зависимости (`funcs`, `space`, …).
         * @param actual контекст этой зависимости.
         * @throws IllegalArgumentException если контексты различаются.
         */
        fun requireSame(
            owner: String,
            expected: NumericsContext,
            dependency: String,
            actual: NumericsContext,
        ) {
            require(expected == actual) {
                "$owner: контекст зависимости '$dependency' не совпадает с контекстом решателя. " +
                    "Решатель: ${expected.describe()}; '$dependency': ${actual.describe()}. " +
                    "Разные контексты значат, что части ОДНОЙ задачи будут посчитаны разными " +
                    "реализациями линейной алгебры, а это молча сдвигает числа. Передайте ОДИН и тот же " +
                    "NumericsContext и в '$dependency', и в решатель."
            }
        }
    }

    /** Короткое описание для сообщений об ошибках. */
    fun describe(): String = "backend=${backend.name}, parallel=$parallel"
}
