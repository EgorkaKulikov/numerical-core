package numerics

import kotlin.math.abs
import kotlin.math.sqrt

/**
 * ЕДИНСТВЕННЫЙ источник дешёвых скалярных и служебных операций плотной линейной
 * алгебры: конструкторы матриц, нормы векторов, разложение Холецкого и мера
 * несимметричности.
 *
 * Зачем отдельный объект, а не код внутри фасада [LinearAlgebra]. У проекта две
 * реализации линейной алгебры: боевой фасад [LinearAlgebra] (делегирует тяжёлые
 * операции подключаемому бэкенду) и эталонный оракул [ReferenceLinearAlgebra],
 * которым тест `LinearAlgebraVsReferenceTest` проверяет фасад. Перечисленные выше
 * операции бэкенда не требуют, и их тела в обоих файлах были ДОСЛОВНО одинаковыми —
 * то есть правка в одном месте молча расходилась бы со вторым.
 *
 * КЛЮЧЕВОЕ ОГРАНИЧЕНИЕ: оракул обязан оставаться НЕЗАВИСИМЫМ от проверяемого кода.
 * Если бы общий код жил в [LinearAlgebra], оракул начал бы ссылаться на фасад (и
 * транзитивно на `Backends`), и тест сверки замкнулся бы сам на себя, потеряв смысл.
 * Поэтому общий код вынесен в третий объект, от которого зависят ОБА, и который сам
 * не зависит ни от фасада, ни от бэкендов.
 *
 * `internal`: это деталь реализации двух объектов-обёрток, а не публичный API
 * библиотеки. Наружу операции по-прежнему доступны через [LinearAlgebra].
 *
 * ВАЛИДАЦИЯ ВХОДА здесь СОЗНАТЕЛЬНО ОТСУТСТВУЕТ — тела содержат только
 * вычислительное ядро. Причина в том, что контракты двух вызывающих РАЗНЫЕ:
 * фасад [LinearAlgebra.maxAsymmetry] обязан отбраковывать пустую/неквадратную/рваную
 * матрицу диагностическим `require` (это проверяется тестом `LinearAlgebraExtraTest`),
 * а оракул исторически этого не делает и менять его поведение нельзя. Разместив
 * проверки здесь, мы либо сломали бы оракул, либо не смогли бы их выполнить в фасаде.
 * Каждый вызывающий добавляет свои проверки ПЕРЕД обращением сюда.
 */
internal object DenseOps {

    /** Создаёт нулевую матрицу размера rows x cols. */
    fun zeros(rows: Int, cols: Int): Array<DoubleArray> = Array(rows) { DoubleArray(cols) }

    /** Единичная матрица размера n x n. */
    fun identity(n: Int): Array<DoubleArray> = Array(n) { i -> DoubleArray(n) { j -> if (i == j) 1.0 else 0.0 } }

    /** Евклидова норма вектора. */
    fun norm2(x: DoubleArray): Double = sqrt(x.fold(0.0) { acc, v -> acc + v * v })

    /** Бесконечная (равномерная) норма вектора. */
    fun normInf(x: DoubleArray): Double = x.fold(0.0) { acc, v -> maxOf(acc, abs(v)) }

    /**
     * Разложение Холецкого A = L L^T для симметричной положительно определённой A.
     * @return нижнетреугольная L или null, если A не положительно определена.
     */
    fun cholesky(a: Array<DoubleArray>): Array<DoubleArray>? {
        val n = a.size
        val l = zeros(n, n)
        for (i in 0 until n) {
            for (j in 0..i) {
                var s = a[i][j]
                for (k in 0 until j) s -= l[i][k] * l[j][k]
                if (i == j) {
                    if (s <= 0.0) return null
                    l[i][j] = sqrt(s)
                } else {
                    l[i][j] = s / l[j][j]
                }
            }
        }
        return l
    }

    /**
     * Вычислительное ядро меры несимметричности max|A - A^T| БЕЗ проверок входа.
     *
     * Индексация идёт по `a.indices` по обоим индексам, поэтому на неквадратной или
     * рваной матрице возможен `ArrayIndexOutOfBoundsException`. Отбраковка таких
     * входов — обязанность вызывающего (см. [LinearAlgebra.maxAsymmetry]).
     */
    fun maxAsymmetry(a: Array<DoubleArray>): Double {
        var m = 0.0
        for (i in a.indices) for (j in a.indices) m = maxOf(m, abs(a[i][j] - a[j][i]))
        return m
    }
}
